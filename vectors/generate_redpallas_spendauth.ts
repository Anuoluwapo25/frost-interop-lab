// Regenerates redpallas_spendauth.json: 2-of-3 FROST signatures made entirely
// by the orchard-rust adapter (ZF reddsa FROST), plus tampered variants. Every
// expected verdict is the orchard crate's own; the script refuses to write a
// vector the TypeScript verifier disagrees on.
//
//   cargo build --release --manifest-path adapters/orchard-rust/Cargo.toml
//   node vectors/generate_redpallas_spendauth.ts

import { randomBytes } from "node:crypto";
import { writeFileSync } from "node:fs";
import { AdapterClient, loadManifests } from "../src/adapter.ts";
import { hex, unhex } from "../src/crypto/hex.ts";
import { bigToLe32, isOnCurveX, leToBig, modQ, Q } from "../src/crypto/pallas.ts";
import { scalarBytes, verifySpendAuth } from "../src/frost.ts";
import { keygen, signRound } from "../src/signing.ts";

type Vector = { rk: string; message: string; signature: string; valid: boolean; why: string };

const rust = new AdapterClient(loadManifests().find((m) => m.name === "orchard-rust")!);
const rand = (n: number) => new Uint8Array(randomBytes(n));
const vectors: Vector[] = [];

for (let i = 0; i < 4; i++) {
  const g = await keygen(rust, 2, 3);
  if ("error" in g) throw new Error(g.error);
  const message = rand(32);
  const r = await signRound({
    group: g, signers: new Map([[1 + (i % 3), rust], [1 + ((i + 1) % 3), rust]]), message,
    alpha: scalarBytes(modQ(leToBig(rand(64)))), verifiers: [rust],
  });
  if (!r.ok) throw new Error(r.problem);
  vectors.push({ rk: r.rk!, message: hex(message), signature: r.signature!, valid: true, why: `2-of-3 FROST signature, signers ${r.signers.map((s) => s.id).join(" and ")}` });
}

const [v0, v1] = vectors;
const sig = unhex(v0.signature);
const tamper = (f: (s: Uint8Array) => void) => {
  const s = sig.slice();
  f(s);
  return hex(s);
};
let offCurve = 0n;
while (isOnCurveX(offCurve)) offCurve++;
const invalid: Omit<Vector, "valid">[] = [
  { ...v0, message: hex(unhex(v0.message).map((b, i) => (i === 0 ? b ^ 1 : b))), why: "message changed by one bit" },
  { ...v0, rk: v1.rk, why: "signature checked against another group's rk" },
  { ...v0, signature: tamper((s) => s.set(bigToLe32(leToBig(s.subarray(32)) + Q), 32)), why: "S + q: non-canonical scalar (malleability)" },
  { ...v0, signature: tamper((s) => (s[31] ^= 0x80)), why: "R with the sign bit flipped" },
  { ...v0, signature: tamper((s) => s.set(bigToLe32(offCurve), 0)), why: "R not on the curve" },
  { ...v0, signature: tamper((s) => s.set(scalarBytes(modQ(leToBig(s.subarray(32)) + 1n)), 32)), why: "S off by one" },
];
for (const v of invalid) vectors.push({ ...v, valid: false });

for (const v of vectors) {
  const official = await rust.request("redpallas_verify", { rk: v.rk, message: v.message, signature: v.signature });
  const ours = verifySpendAuth(unhex(v.rk), unhex(v.message), unhex(v.signature));
  if (official.valid !== v.valid || ours !== v.valid) throw new Error(`verdict mismatch on "${v.why}": orchard ${official.valid}, lab ${ours}`);
}
rust.close();

writeFileSync(new URL("./redpallas_spendauth.json", import.meta.url), JSON.stringify({
  suite: "redpallas_verify",
  source: "Signed by the orchard-rust adapter: ZF FROST(Pallas, BLAKE2b-512) from reddsa 0.5.2 with frost-rerandomized 3.0.0. Verdicts from orchard 0.15.5 primitives::redpallas::VerificationKey<SpendAuth>::verify.",
  provenance: "Generated by vectors/generate_redpallas_spendauth.ts. rk is the randomized group key ak + [alpha]G, message a random 32-byte stand-in for a sighash.",
  vectors,
}, null, 2) + "\n");
console.log(`wrote ${vectors.length} vectors`);
